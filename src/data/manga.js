// Generate dummy chapters per manga (no API calls)
export function getChaptersFor(mangaId) {
  const manga = MANGA.find((m) => m.id === mangaId);
  if (!manga) return [];
  const total = Math.min(manga.chapters, 30); // show last 30 chapters max in list
  const start = manga.chapters - total + 1;
  const chapters = [];
  for (let i = start; i <= manga.chapters; i++) {
    const daysAgo = manga.chapters - i;
    const d = new Date();
    d.setDate(d.getDate() - daysAgo * 7);
    chapters.push({
      number: i,
      title: i === manga.chapters ? "Epilog Pertarungan" : `Chapter ${i}`,
      date: d.toISOString().slice(0, 10),
      pages: 18 + ((i * 7) % 14),
      isNew: daysAgo <= 1,
      isLocked: false,
    });
  }
  return chapters.reverse();
}

export function getMangaById(id) {
  return MANGA.find((m) => m.id === id);
}

export function getRelatedManga(manga, limit = 6) {
  return MANGA.filter(
    (m) =>
      m.id !== manga.id && m.genres.some((g) => manga.genres.includes(g))
  ).slice(0, limit);
}

export function searchManga(query) {
  const q = query.trim().toLowerCase();
  if (!q) return MANGA;
  return MANGA.filter(
    (m) =>
      m.title.toLowerCase().includes(q) ||
      m.altTitle.toLowerCase().includes(q) ||
      m.author.toLowerCase().includes(q) ||
      m.synopsis.toLowerCase().includes(q)
  );
}

export function formatNumber(n) {
  if (n >= 1_000_000) return (n / 1_000_000).toFixed(1) + "M";
  if (n >= 1_000) return (n / 1_000).toFixed(1) + "K";
  return String(n);
}
